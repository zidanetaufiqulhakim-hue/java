public class LuasSegitiga {
    // Program menghitung luas segitiga
    public static void main(String[] args){
        // storage
        double tinggi = 0;
        double alas = 0;
        double luas = 0;

        //input
        tinggi = 17.0;
        alas = 25.0;

        //process
        luas = 0.5 * alas * tinggi;

        //output
        System.out.println("Luas Segitaga = " + luas);
    }
}
//OutputLuas Segitaga = 212.5